"""Lighting metadata and tiny lookup tables; reuse the accepted native artwork."""
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'art/accepted-basalt'
OUT=ROOT/'resources/tiles'
THEMES=['morning','day','sunset','night']

def nearest(v): return min(255,max(0,int(v+42)//85*85))
def packed(rgb):
 r,g,b=map(nearest,rgb)
 return 0xc0|(r//85)<<4|(g//85)<<2|(b//85)
def illumination(rgb,theme,sky):
 r,g,b=rgb; l=(r+g+b)/3
 if sky:
  cloudy=min(rgb)>=170
  if theme=='night':
   return packed((85,85,170) if cloudy else (0,0,85))
  if theme=='sunset':
   if cloudy: return packed((255,225,150))
   if r>=170 and g>=85: return packed((r,g,b*.75))
   return packed((170 if l<140 else 255,85 if l<140 else 140,170 if l<140 else 140))
  if theme=='morning':
   if cloudy: return packed((255,255,205))
   if r>=170 and g>=85: return packed((255,190,max(90,b)))
   return packed((r+25,g+15,b))
  # Day: replace the 1's baked sunset sky with blue and pale cloud light.
  if cloudy: return packed((225,255,255))
  if r>=170 and g>=85: return packed((85,170,255))
  return packed(rgb)
 if theme=='day': return packed(rgb)
 if theme=='morning': return packed((r*1.02+12,g*.97+8,b*.90))
 if theme=='sunset': return packed((r*.9+25,g*.78,b*.72+8))
 # Night: cool shadows, substantially dimmer plants/petals and rock highlights.
 if g>r and g>=b: return packed((r*.42,max(85,g*.56),b*.48+25))
 return packed((r*.52,g*.56,b*.60+20))

tables=[]
for theme in THEMES:
 roles=[]
 for sky in [False,True]:
  roles.append([illumination((((c>>4)&3)*85,((c>>2)&3)*85,(c&3)*85),theme,sky) for c in range(64)])
 tables.append(roles)
lines=['/* Generated by tools/prepare_lighting.py: theme, foreground/sky, RGB6 */',
       'static const uint8_t LIGHTING[4][2][64] = {']
for roles in tables:
 lines.append(' {'+',\n  '.join('{'+','.join(hex(v) for v in role)+'}' for role in roles)+'},')
lines.append('};\n')
(ROOT/'src/c/lighting.h').write_text('\n'.join(lines))

def is_sky(n,x,y,rgb):
 r,g,b=rgb
 # Compact, scene-specific sky boundaries. Plants and colored petals are
 # excluded, preventing a whole-image tint from recoloring every subject.
 creamy=min(rgb)>=170
 cool=b>=170 and g>=170 and r<=170
 if n==1: return y<60 and r>=170 and g>=85
 if n==0: return (y<39 and (cool or creamy or b>r)) or (y<49 and cool)
 if n==4: return y<61 and (cool or creamy)
 if n==2: return y<44 and (cool or creamy)
 if n in [3,5,6,7,8,9]:
  # Restrict sky to blue-dominant colors: white architecture/feathers stay foreground.
  limits={3:36,5:53,6:63,7:12,8:17,9:45}
  return y<limits[n] and b>r and b>=g and b>=170
 return False

for n in [1,0,4,2]:
 raw=bytearray((SOURCE/f'digit_{n}_v0.bin').read_bytes())
 for i,v in enumerate(raw):
  if v<0xc0: continue
  rgb=(((v>>4)&3)*85,((v>>2)&3)*85,(v&3)*85)
  if is_sky(n,i%32,i//32,rgb): raw[i]=0x80|(v&0x3f)
 (OUT/f'digit_{n}_v0.bin').write_bytes(raw)
print('Added sky/foreground lighting roles without increasing tile bytes; lookup tables 512 bytes.')


